from pathlib import Path
import hashlib
import sys
src = Path(sys.argv[1])
out = Path(sys.argv[2])
digest = hashlib.sha256(src.read_bytes()).hexdigest()
out.write_text(f"{digest}  {src.name}\n", encoding="utf-8")
PY_CHECKSUM
fi
